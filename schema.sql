-- MotoRide. Проектный PostgreSQL DDL, восстановленный по JPA-аннотациям.
-- Составной PK таблицы связи и индексы внешних ключей добавлены как проектные решения.

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE technologies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT
);

CREATE TABLE motorcycles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id),
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    engine_cc INTEGER NOT NULL,
    horsepower INTEGER NOT NULL,
    badge VARCHAR(100),
    short_description VARCHAR(255),
    description TEXT,
    image_url VARCHAR(500),
    price NUMERIC(12,2),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE motorcycle_technologies (
    motorcycle_id BIGINT NOT NULL REFERENCES motorcycles(id),
    technology_id BIGINT NOT NULL REFERENCES technologies(id),
    PRIMARY KEY (motorcycle_id, technology_id)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorcycle_id BIGINT NOT NULL REFERENCES motorcycles(id),
    rating INTEGER NOT NULL,
    text TEXT,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorcycle_id BIGINT NOT NULL REFERENCES motorcycles(id),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    image_url VARCHAR(500),
    published_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_motorcycles_category_id ON motorcycles(category_id);
CREATE INDEX idx_reviews_motorcycle_id ON reviews(motorcycle_id);
CREATE INDEX idx_favorites_motorcycle_id ON favorites(motorcycle_id);
CREATE INDEX idx_motorcycle_technologies_technology_id ON motorcycle_technologies(technology_id);
